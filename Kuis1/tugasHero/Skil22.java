package tugasHero;

public class Skil22 {

    private String nama;
    private int damage;
    private int energi;

    public Skil22(String nama, int damage, int energi) {
        this.nama = nama;
        this.damage = damage;
        this.energi = energi;
    }

    public String getNama() {
        return nama;
    }

    public int getDamage() {
        return damage;
    }

    public int getEnergi() {
        return energi;
    }
}